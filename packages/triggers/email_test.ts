Deno.test("triggersFromConfig: builds the pulled transports, fails loudly on missing secrets", () => {
  const env: Record<string, string> = {
    IMAP_PASSWORD: "pw",
    GMAIL_CLIENT_SECRET: "cs",
    GMAIL_REFRESH_TOKEN: "grt",
    OUTLOOK_REFRESH_TOKEN: "ort",
  };
  const triggers = triggersFromConfig(PULLED_CONFIG, (n) => env[n]);
  assertEquals(triggers.map((t) => t.name), ["email", "email", "email"]);

  const without = (name: string) => (n: string) => n === name ? undefined : env[n];
  for (const name of Object.keys(env)) {
    assertThrows(() => triggersFromConfig(PULLED_CONFIG, without(name)), Error, name);
  }
});

Deno.test("config: pulled-transport defaults apply", () => {
  const [imap, gmail, outlook] = PULLED_CONFIG.triggers!;
  if (imap.type !== "email" || imap.transport !== "imap") throw new Error("expected imap");
  assertEquals(imap.port, 993);
  assertEquals(imap.smtp_port, 465);
  assertEquals(imap.folder, "INBOX");
  assertEquals(imap.poll_seconds, 60);
  if (gmail.type !== "email" || gmail.transport !== "gmail") throw new Error("expected gmail");
  assertEquals(gmail.label, "INBOX");
  assertEquals(gmail.client_secret_env, "GMAIL_CLIENT_SECRET");
  assertEquals(gmail.refresh_token_env, "GMAIL_REFRESH_TOKEN");
  if (outlook.type !== "email" || outlook.transport !== "outlook") {
    throw new Error("expected outlook");
  }
  assertEquals(outlook.tenant, "common");
  assertEquals(outlook.folder, "inbox");
  assertEquals(outlook.client_secret_env, undefined);
  assertEquals(outlook.refresh_token_env, "OUTLOOK_REFRESH_TOKEN");
});
