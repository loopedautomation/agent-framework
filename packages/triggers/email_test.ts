Deno.test("addressAllowed: exact match, case-insensitive, display-name form", () => {
  const patterns = ["petra@example.com"];
  assert(addressAllowed("petra@example.com", patterns));
  assert(addressAllowed("Petra@Example.COM", patterns));
  assert(addressAllowed("Petra Lang <petra@example.com>", patterns));
  assert(!addressAllowed("someone@example.com", patterns));
});

Deno.test("addressAllowed: *@domain matches the domain, no subdomains, * matches anyone", () => {
  assert(addressAllowed("anyone@example.com", ["*@example.com"]));
  assert(!addressAllowed("anyone@mail.example.com", ["*@example.com"]));
  assert(!addressAllowed("anyone@notexample.com", ["*@example.com"]));
  assert(addressAllowed("total@stranger.net", ["*"]));
});

Deno.test("isAutoGenerated: Auto-Submitted and bulk Precedence drop; normal mail passes", () => {
  assert(isAutoGenerated({ "Auto-Submitted": "auto-replied" }));
  assert(isAutoGenerated({ "auto-submitted": "auto-generated" }));
  assert(!isAutoGenerated({ "Auto-Submitted": "no" }));
  assert(isAutoGenerated({ Precedence: "bulk" }));
  assert(isAutoGenerated({ precedence: "list" }));
  assert(!isAutoGenerated({ Precedence: "first-class" }));
  assert(!isAutoGenerated({}));
});

Deno.test("threadKey: root Message-ID from References, then In-Reply-To, then own id", () => {
  const base: ResendReceivedEmail = { from: "petra@example.com", message_id: "<own@ex>" };
  assertEquals(
    threadKey({
      ...base,
      headers: { References: "<root@ex> <mid@ex>", "In-Reply-To": "<mid@ex>" },
    }),
    "email:<root@ex>",
  );
  assertEquals(threadKey({ ...base, headers: { "in-reply-to": "<mid@ex>" } }), "email:<mid@ex>");
  assertEquals(threadKey(base), "email:<own@ex>");
});

Deno.test("threadKey: fallback normalizes subject and counterpart", () => {
  const a = threadKey({ from: "petra@example.com", subject: "Invoice 42" });
  const b = threadKey({ from: "Petra <PETRA@example.com>", subject: "Re: re: invoice 42" });
  assertEquals(a, b);
  assertEquals(a, "email:invoice 42|petra@example.com");
});

Deno.test("renderEmail: headers, text body, attachment listing; HTML fallback strips tags", () => {
  const text = renderEmail({
    from: "petra@example.com",
    to: ["agent@example.com"],
    subject: "Invoice 42",
    created_at: "2026-07-07T09:00:00Z",
    text: "Please file this.",
    attachments: [{ filename: "invoice.pdf", content_type: "application/pdf", size: 1234 }],
  });
  assert(text.includes("From: petra@example.com"));
  assert(text.includes("Subject: Invoice 42"));
  assert(text.includes("Please file this."));
  assert(text.includes("[attachment: invoice.pdf (application/pdf, 1234 bytes) — not delivered]"));

  const html = renderEmail({
    from: "a@b.c",
    html: "<div><p>Hello &amp; welcome</p><br><script>evil()</script></div>",
  });
  assert(html.includes("Hello & welcome"));
  assert(!html.includes("evil"));
  assert(!html.includes("<p>"));
});

