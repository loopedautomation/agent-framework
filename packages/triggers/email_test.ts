// The trigger end to end, against a fake Resend API

/** The JSON Resend's receiving API serves: attachment bytes ride along as base64. */
const RECEIVED: Record<string, unknown> = {
  from: "Petra Lang <petra@example.com>",
  to: ["agent@example.com"],
  reply_to: [],
  subject: "Invoice 42",
  created_at: "2026-07-07T09:00:00Z",
  text: "Please file the attached invoice.",
  headers: { "Message-Id": "<orig@example.com>" },
  message_id: "<orig@example.com>",
  attachments: [
    { filename: "shot.png", content_type: "image/png", size: 70, content: PNG_BASE64 },
    { filename: "invoice.pdf", content_type: "application/pdf", size: 1234, content: btoa("%PDF") },
  ],
};

/** A fake api.resend.com: serves the received email, captures reply sends. */
function fakeResendApi(email: Record<string, unknown>) {
  const sent: { body: Record<string, unknown> }[] = [];
  let port = 0;
  const server = Deno.serve({ port: 0, onListen: (a) => (port = a.port) }, async (req) => {
    const url = new URL(req.url);
    if (req.method === "GET" && url.pathname.startsWith("/emails/receiving/")) {
      return Response.json(email);
    }
    if (req.method === "POST" && url.pathname === "/emails") {
      sent.push({ body: await req.json() });
      return Response.json({ id: "sent_1" });
    }
    return Response.json({ error: "unexpected" }, { status: 500 });
  });
  return { sent, apiBase: () => `http://127.0.0.1:${port}`, close: () => server.shutdown() };
}

function runResult(reply: string): RunResult {
  return {
    status: "ok",
    reply,
    steps: 1,
    usage: { inputTokens: 1, outputTokens: 1 },
    messages: [],
  };
}

async function startTrigger(
  api: { apiBase: () => string },
  emit: (event: AgentEvent) => Promise<RunResult>,
  overrides: Partial<ConstructorParameters<typeof EmailTrigger>[0]> = {},
) {
  let port = 0;
  const trigger = new EmailTrigger({
    path: "/email",
    port: 0,
    signingSecret: SECRET,
    apiKey: "re_test",
    fromAddresses: ["*@example.com"],
    media: MEDIA,
    onListen: (a) => (port = a.port),
    apiBase: api.apiBase(),
    ...overrides,
  });
  await trigger.start(emit);
  return { trigger, url: () => `http://127.0.0.1:${port}/email` };
}

async function postWebhook(url: string, payload: unknown, opts: { badSig?: boolean } = {}) {
  const body = JSON.stringify(payload);
  const timestamp = String(Math.floor(Date.now() / 1000));
  const sig = opts.badSig ? "Zm9yZ2Vk" : await sign("msg_1", timestamp, body);
  return await fetch(url, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      "svix-id": "msg_1",
      "svix-timestamp": timestamp,
      "svix-signature": `v1,${sig}`,
    },
    body,
  });
}

const INBOUND = {
  type: "email.received",
  data: {
    email_id: "rcv_1",
    from: "Petra Lang <petra@example.com>",
    to: ["agent@example.com"],
    subject: "Invoice 42",
    message_id: "<orig@example.com>",
  },
};

Deno.test("email: verified webhook wakes the agent and the reply threads back", async () => {
  const api = fakeResendApi(RECEIVED);
  const events: AgentEvent[] = [];
  const { trigger, url } = await startTrigger(api, (event) => {
    events.push(event);
    return Promise.resolve(runResult("Filed it."));
  });

  // Unsigned/forged POSTs never reach the parser.
  const forged = await postWebhook(url(), INBOUND, { badSig: true });
  assertEquals(forged.status, 401);
  await forged.body?.cancel();

  const res = await postWebhook(url(), INBOUND);
  assertEquals(res.status, 202);
  await res.body?.cancel();

  await trigger.stop(); // drains the in-flight run
  await api.close();

  assertEquals(events.length, 1);
  assert(events[0].input.includes("Subject: Invoice 42"));
  assert(events[0].input.includes("Please file the attached invoice."));
  assertEquals(events[0].conversationKey, "email:<orig@example.com>");

  // The PNG rode Resend's payload to the model; the PDF is prose.
  assertEquals(events[0].images?.length, 1);
  assertEquals(events[0].images?.[0].data, PNG_BASE64);
  assert(events[0].input.includes("[attachment: invoice.pdf"));
  assert(!events[0].input.includes("shot.png"));

  assertEquals(api.sent.length, 1);
  const reply = api.sent[0].body;
  assertEquals(reply.from, "agent@example.com");
  assertEquals(reply.to, ["Petra Lang <petra@example.com>"]);
  assertEquals(reply.subject, "Re: Invoice 42");
  assertEquals(reply.text, "Filed it.");
  assertEquals((reply.headers as Record<string, string>)["In-Reply-To"], "<orig@example.com>");
});

Deno.test("email: unlisted senders and foreign event types are ignored without a run", async () => {
  const api = fakeResendApi(RECEIVED);
  let runs = 0;
  const { trigger, url } = await startTrigger(api, () => {
    runs++;
    return Promise.resolve(runResult("nope"));
  }, { fromAddresses: ["only@this-address.com"] });

  const stranger = await postWebhook(url(), INBOUND);
  assertEquals(stranger.status, 200);
  assertEquals((await stranger.json()).ignored, "sender not allowed");

  const delivered = await postWebhook(url(), { type: "email.delivered", data: { email_id: "x" } });
  assertEquals(delivered.status, 200);
  await delivered.body?.cancel();

  await trigger.stop();
  await api.close();
  assertEquals(runs, 0);
  assertEquals(api.sent.length, 0);
});

Deno.test("email: an oversized body is refused before the signature is checked", async () => {
  const api = fakeResendApi(RECEIVED);
  let runs = 0;
  const { trigger, url } = await startTrigger(api, () => {
    runs++;
    return Promise.resolve(runResult("nope"));
  });

  // The webhook carries metadata only, so nothing real approaches a megabyte.
  // The svix headers are deliberately forged: 413 rather than 401 is the proof
  // that the read gave up before the body was verified, which is the only
  // ordering that bounds what an unauthenticated POST can put in memory.
  const res = await fetch(url(), {
    method: "POST",
    headers: {
      "content-type": "application/json",
      "svix-id": "msg_1",
      "svix-timestamp": String(Math.floor(Date.now() / 1000)),
      "svix-signature": "v1,Zm9yZ2Vk",
    },
    body: new Uint8Array(2 * 1024 * 1024),
  });
  assertEquals(res.status, 413);
  await res.body?.cancel();

  await trigger.stop();
  await api.close();
  assertEquals(runs, 0);
  assertEquals(api.sent.length, 0);
});

Deno.test("email: auto-generated mail is dropped after the body fetch", async () => {
  const api = fakeResendApi({ ...RECEIVED, headers: { "Auto-Submitted": "auto-replied" } });
  let runs = 0;
  const { trigger, url } = await startTrigger(api, () => {
    runs++;
    return Promise.resolve(runResult("nope"));
  });
  const res = await postWebhook(url(), INBOUND);
  assertEquals(res.status, 202);
  await res.body?.cancel();
  await trigger.stop();
  await api.close();
  assertEquals(runs, 0);
});

Deno.test("email: allow_silence sends nothing on NO_REPLY", async () => {
  const api = fakeResendApi(RECEIVED);
  const { trigger, url } = await startTrigger(
    api,
    () => Promise.resolve(runResult(NO_REPLY)),
    { allowSilence: true },
  );
  const res = await postWebhook(url(), INBOUND);
  assertEquals(res.status, 202);
  await res.body?.cancel();
  await trigger.stop();
  await api.close();
  assertEquals(api.sent.length, 0);
});

