// Signature verification

const SECRET = "whsec_" + btoa("test-signing-key");

async function sign(id: string, timestamp: string, body: string): Promise<string> {
  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode("test-signing-key"),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const sig = await crypto.subtle.sign(
    "HMAC",
    key,
    new TextEncoder().encode(`${id}.${timestamp}.${body}`),
  );
  return btoa(String.fromCharCode(...new Uint8Array(sig)));
}

Deno.test("verifySvixSignature: valid signature passes, tampered body fails", async () => {
  const now = 1_750_000_000;
  const body = '{"type":"email.received"}';
  const sig = await sign("msg_1", String(now), body);
  const base = { secret: SECRET, id: "msg_1", timestamp: String(now), nowSeconds: now };
  assert(await verifySvixSignature({ ...base, signature: `v1,${sig}`, body }));
  // Additional unknown signatures are fine as long as one v1 entry matches.
  assert(await verifySvixSignature({ ...base, signature: `v2,bogus v1,${sig}`, body }));
  assert(!await verifySvixSignature({ ...base, signature: `v1,${sig}`, body: body + " " }));
  assert(!await verifySvixSignature({ ...base, signature: "v1,bm90LXRoZS1zaWc=", body }));
});

Deno.test("verifySvixSignature: stale timestamps are rejected", async () => {
  const now = 1_750_000_000;
  const body = "{}";
  const stale = String(now - 3600);
  const sig = await sign("msg_1", stale, body);
  assert(
    !await verifySvixSignature({
      secret: SECRET,
      id: "msg_1",
      timestamp: stale,
      signature: `v1,${sig}`,
      body,
      nowSeconds: now,
    }),
  );
});

