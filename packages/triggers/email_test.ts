Deno.test("renderEmailInput: an image reaches the model, a PDF becomes a note", async () => {
  const { input, images } = await renderEmailInput({
    from: "petra@example.com",
    subject: "Invoice 42",
    text: "Please file this.",
    attachments: [
      {
        filename: "shot.png",
        mediaType: "image/png",
        size: 70,
        fetch: () => Promise.resolve(bytesOf(PNG_BASE64)),
      },
      {
        filename: "invoice.pdf",
        mediaType: "application/pdf",
        size: 1234,
        fetch: () => Promise.reject(new Error("never called for a PDF")),
      },
    ],
  }, MEDIA);

  assertEquals(images.length, 1);
  assertEquals(images[0].mediaType, "image/png");
  assertEquals(images[0].data, PNG_BASE64);
  assert(input.includes("Please file this."));
  assert(!input.includes("shot.png")); // the agent can see it; no prose needed
  assert(input.includes("[attachment: invoice.pdf (application/pdf, 1 KB)"));
});

Deno.test("renderEmailInput: an oversized image is named, never fetched", async () => {
  let fetched = false;
  const { input, images } = await renderEmailInput({
    from: "petra@example.com",
    attachments: [{
      filename: "huge.png",
      mediaType: "image/png",
      size: 9_000_000,
      fetch: () => {
        fetched = true;
        return Promise.resolve(new Uint8Array(9_000_000));
      },
    }],
  }, MEDIA);
  assertEquals(images.length, 0);
  assert(!fetched);
  assert(input.includes("huge.png"));
  assert(input.includes("limit"));
});

