const EMAIL_CONFIG = parseAgentConfig(`
handle: mail-bot
description: email trigger test agent
model:
  provider: openai-compatible
  id: test-model
purpose: test
triggers:
  - type: email
    transport: resend
    from_addresses: ["*@example.com"]
`);

Deno.test("triggersFromConfig: builds the email trigger, fails loudly on missing secrets", () => {
  const env: Record<string, string> = {
    RESEND_WEBHOOK_SECRET: "whsec_abc",
    RESEND_API_KEY: "re_123",
  };
  const triggers = triggersFromConfig(EMAIL_CONFIG, (n) => env[n]);
  assertEquals(triggers.map((t) => t.name), ["email"]);

  const without = (name: string) => (n: string) => n === name ? undefined : env[n];
  assertThrows(
    () => triggersFromConfig(EMAIL_CONFIG, without("RESEND_WEBHOOK_SECRET")),
    Error,
    "RESEND_WEBHOOK_SECRET",
  );
  assertThrows(
    () => triggersFromConfig(EMAIL_CONFIG, without("RESEND_API_KEY")),
    Error,
    "RESEND_API_KEY",
  );
});

Deno.test("config: from_addresses is required and defaults apply", () => {
  const err = assertThrows(() =>
    parseAgentConfig(`
handle: mail-bot
description: x
model:
  provider: openai-compatible
  id: test-model
purpose: test
triggers:
  - type: email
    transport: resend
`)
  );
  assert(String(err).includes("from_addresses"));

  const t = EMAIL_CONFIG.triggers![0];
  if (t.type !== "email") throw new Error("expected email trigger");
  assertEquals(t.path, "/email");
  assertEquals(t.port, 8080);
  assertEquals(t.signing_secret_env, "RESEND_WEBHOOK_SECRET");
  assertEquals(t.api_key_env, "RESEND_API_KEY");
  assertEquals(t.allow_silence, false);
});
